import fs from 'node:fs';

// The historical migration modules remain the editable/auditable source of truth.
// Runtime code consumes generated snapshots instead of importing every generation.
await import('../legacy/recipe-migrations/recipe-migration-registry.js');
const { migratedNoteKeys, migratedRecipes } = await import('../legacy/recipe-migrations/recipe-migrations.js');

const noteKeys = [...migratedNoteKeys];
const payload = {
  version: 1,
  noteKeys,
  recipes: migratedRecipes,
};

fs.writeFileSync('public/promoted-recipes.json', JSON.stringify(payload));
fs.writeFileSync(
  'public/promoted-note-keys.js',
  `// Generated by scripts/generate-promoted-recipes.mjs. Do not edit by hand.\nconst keys=new Set(${JSON.stringify(noteKeys)});\nexport const isMigratedNote=record=>keys.has(\`${'${record?.source}-${record?.index}'}\`);\n`,
);
console.log(`Generated promoted runtime data: ${payload.recipes.length} recipes, ${noteKeys.length} note keys`);
